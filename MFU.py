# 第二層：資料結構和流程

# 需要記錄記憶體中每一頁的三項資料，可以用三個 dict，key 都是頁號：
# - count：存取次數，也可以用來判斷這一頁在不在記憶體裡（就像 FIFO 裡的 dirty）。
# - dirty：dirty bit。
# - load_time：載入時間，平手時要用。可以用 for i, (page, is_write) in enumerate(refs) 裡的 i 當作時間。

# 這次不需要 deque，因為換出的對象不是看順序，而是看 count。

# 每次存取的流程：
# - hit：count 加 1。
# - fault：fault 和中斷各加 1 → 記憶體滿了的話找出受害頁、刪掉它的三項紀錄、dirty 就寫回 → 把新頁放進去：count = 1、dirty = False、記錄 load_time。
# - 最後，如果是寫入，就把 dirty 設成 True，和 FIFO 一樣。

# 函式的參數和回傳值都要和 fifo() 一樣，(refs, n_frames) → (faults, interrupts, disk_writes)，這樣 print_results 才能直接用。

